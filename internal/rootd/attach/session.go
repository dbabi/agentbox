// Paths inside the session (Appendix C's container layout).
const (
	Home      = controlpaths.Home
	Workspace = controlpaths.Workspace
	Exports   = "/opt/agentbox/exports"
	CodexHome = "/run/agentbox-attach/codex" // a fresh dir per session: Codex keeps no state in session-home but auth.json
)

// Root is /var/lib/agentbox on the box; tests pass a temp dir.
const Root = "/var/lib/agentbox"

// SettingsFile is the generated Claude settings for attach (§4.2, Appendix C "Exports"): --settings points at it, and
// rootd bind-mounts it read-only over session-home's ~/.claude/settings.json, so a session can't persist hooks there.
// disableAllHooks takes precedence over project and local settings, so a workspace SessionStart hook never runs even
// if session-home's ~/.claude.json trusts the workspace. Auto memory is off: MEMORY.md in session-home would load into
// every later session. It is also the managed settings (below), so it carries task.ClaudeManaged.
const SettingsFile = "claude-settings-attach.json"

var settings = func() map[string]any {
	m := maps.Clone(task.ClaudeManaged)
	m["autoMemoryEnabled"] = false
	m["env"] = map[string]string{"CLAUDE_CODE_DISABLE_AUTO_MEMORY": "1"}
	return m
}()

// CodexConfig is the generated CODEX_HOME config: no [projects] entries, so no workspace is trusted (§4.2), and the
// task's switches; the task image's requirements.toml holds them too.
const CodexConfig = "# Generated by agentbox-rootd for agent.attach (ARCHITECTURE.md §4.2): it trusts no project.\n" + task.CodexQuiet

// ManagedDir is Claude Code's managed settings dir on Linux. A managed-mcp.json there would make Claude refuse
// --strict-mcp-config, so the attach settings' empty allowedMcpServers does that job instead.
const ManagedDir = "/etc/claude-code"

// NoHooks is the empty dir core.hooksPath names, in tasks and in attach.
const NoHooks = "nohooks"

// GitEnv is the command-line-precedence git config of attach sessions (§4.2, Appendix C; task.Argv sets the first two
// and the last for tasks, whose HOME holds no login): repo-local
// .git/config can't re-enable hooks or fsmonitor, or name its own pager, editor or ssh command, and git finds no bare
// repo by itself. Filters, aliases and diff drivers can't be pinned this way; the control-path gate covers them (.git/
// and every git dir are control paths).
var GitEnv = []string{
	"GIT_CONFIG_COUNT=7",
	"GIT_CONFIG_KEY_0=core.hooksPath", "GIT_CONFIG_VALUE_0=" + Exports + "/" + NoHooks,
	"GIT_CONFIG_KEY_1=core.fsmonitor", "GIT_CONFIG_VALUE_1=false",
	"GIT_CONFIG_KEY_2=core.pager", "GIT_CONFIG_VALUE_2=less",
	"GIT_CONFIG_KEY_3=core.editor", "GIT_CONFIG_VALUE_3=vi",
	"GIT_CONFIG_KEY_4=sequence.editor", "GIT_CONFIG_VALUE_4=vi",
	"GIT_CONFIG_KEY_5=core.sshCommand", "GIT_CONFIG_VALUE_5=ssh",
	"GIT_CONFIG_KEY_6=safe.bareRepository", "GIT_CONFIG_VALUE_6=explicit",
}

// GitConfigs are git's per-user config files in session-home; EmptyGitConfig, in the exports, is bound read-only over
// both.
var GitConfigs = []string{".gitconfig", ".config/git/config"}

const EmptyGitConfig = "gitconfig-empty"

// sessionEnv keeps session-home's dotfiles from running: session-home is agent-writable and persistent, so a session
// could plant code there for every later attach. Git reads no ~/.gitconfig, readline no ~/.inputrc (a macro can type
// a command), and bash no startup file (CLIs: --noprofile --norc).
var sessionEnv = []string{"GIT_CONFIG_GLOBAL=/dev/null", "INPUTRC=/dev/null", "BASH_ENV=", "ENV="}

// CLIs is what an attach can run. Each argv starts with the lockdown flags; the admin's extra arguments follow.
var CLIs = map[string][]string{
	"claude": {"claude", "--setting-sources", "user", "--strict-mcp-config", "--settings", Exports + "/" + SettingsFile},
	"codex":  {"codex"},
	"bash":   {"bash", "--noprofile", "--norc", "-i"},
}

// Mount is one bind mount into the session.
type Mount struct {
	Src, Dst string
	RO       bool
}

// Session is everything the container side needs to start one attach session.
type Session struct {
	ID       string // ses_<ULID>
	Agent    string
	UID, GID int
	TTY      string // the PTY slave rootd owns, /dev/pts/<n>
	Mounts   []Mount
	Env      []string
	Argv     []string
	Dir      string // working directory
}

// Runner starts a session and returns once it and every process it started are gone. Podman is the real one.
type Runner interface {
	Run(ctx context.Context, s Session) error
	Stop(agent, id string) error // a session left running when rootd stopped mid-attach
}

var agentRe = regexp.MustCompile(`^[a-z][a-z0-9-]{0,31}$`)

// Paths of one agent's attach.
type Paths struct {
	SessionHome, Workspace, Exports, Run, Codex string
}

// AgentPaths: §4.1's subvolumes, the exports the task launcher mounts too, and a per-session dir (under control/:
// rootd's ProtectSystem=strict leaves /run read-only).
func AgentPaths(root, agent, id string) Paths {
	run := filepath.Join(root, "control", "attach", id)
	return Paths{
		SessionHome: filepath.Join(root, "data", "agents", agent, "session-home"),
		Workspace:   filepath.Join(root, "data", "workspaces", agent),
		Exports:     filepath.Join(root, "control", "exports", agent),
		Run:         run,
		Codex:       filepath.Join(run, "codex"),
	}
}

// WriteExports writes the attach exports for one agent (root-owned, read-only to the session).
func WriteExports(dir string) error {
	// explicit modes: rootd runs with UMask=0077, and the session's uid must read these
	for _, d := range []string{filepath.Dir(dir), dir, filepath.Join(dir, NoHooks)} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
		if err := os.Chmod(d, 0o755); err != nil {
			return err
		}
	}
	b, _ := json.MarshalIndent(settings, "", "  ")
	for name, body := range map[string][]byte{SettingsFile: append(b, '\n'), "codex-config.toml": []byte(CodexConfig), EmptyGitConfig: nil} {
		if err := writeFile(filepath.Join(dir, name), body); err != nil {
			return err
		}
	}
	return nil
}

func writeFile(p string, b []byte) error {
	if fi, err := os.Stat(p); err == nil && fi.Mode().Perm() == 0o644 {
		if old, err := os.ReadFile(p); err == nil && string(old) == string(b) {
			return nil
		}
	}
	t := p + ".new"
	if err := os.WriteFile(t, b, 0o644); err != nil {
		return err
	}
	if err := os.Chmod(t, 0o644); err != nil {
		return err
	}
	return os.Rename(t, p)
}

// Prepare checks session-home and builds the session. Session-home is agent-writable, so rootd opens every path in it
// with O_NOFOLLOW from the dir itself: a symlink planted there can't make rootd create or follow anything outside it.
func Prepare(root, id, agent, cli string, extra []string, uid, gid int, tty, term string) (Session, error) {
	if !agentRe.MatchString(agent) {
		return Session{}, errors.New("bad agent name")
	}
	argv, ok := CLIs[cli]
	if !ok {
		return Session{}, fmt.Errorf("unknown cli %q (claude, codex or bash)", cli)
	}
	for _, a := range extra {
		if f, _, _ := strings.Cut(a, "="); slices.Contains(task.DeniedFlags, f) {
			return Session{}, fmt.Errorf("refused: %s turns off a policy the session runs under", f)
		}
	}
	p := AgentPaths(root, agent, id)
	if err := homeOwned(p.SessionHome, uid); err != nil {
		return Session{}, err
	}
	for _, rel := range append([]string{".claude/settings.json"}, GitConfigs...) {
		if err := fileMountpoint(p.SessionHome, rel, uid, gid); err != nil {
			return Session{}, err
		}
	}
	if fi, err := os.Lstat(p.Workspace); err != nil || !fi.IsDir() {
		return Session{}, fmt.Errorf("no workspace dir %s", p.Workspace)
	}
	if err := WriteExports(p.Exports); err != nil {
		return Session{}, err
	}
	if err := codexHome(p, uid, gid); err != nil {
		return Session{}, err
	}
	if term == "" || !regexp.MustCompile(`^[A-Za-z0-9._+-]{1,64}$`).MatchString(term) {
		term = "xterm-256color"
	}
	env := append([]string{
		"HOME=" + Home, "USER=ag-" + agent, "LOGNAME=ag-" + agent, "TERM=" + term, "LANG=C.UTF-8",
		"PATH=/usr/local/bin:/usr/bin:/bin", "SHELL=/bin/bash", "CODEX_HOME=" + CodexHome,
		"CLAUDE_CODE_DISABLE_AUTO_MEMORY=1",
	}, append(append(sessionEnv, task.ClaudeQuiet...), GitEnv...)...)
	return Session{
		ID: id, Agent: agent, UID: uid, GID: gid, TTY: tty, Dir: Workspace, Env: env,
		Argv: append(append([]string{}, argv...), extra...),
		Mounts: []Mount{
			{Src: p.SessionHome, Dst: Home},
			// ~/.claude on itself: a mount point can't be renamed or removed, so the settings bind can't be moved aside
			{Src: filepath.Join(p.SessionHome, ".claude"), Dst: Home + "/.claude"},
			{Src: filepath.Join(p.Exports, SettingsFile), Dst: Home + "/.claude/settings.json", RO: true},
			// managed settings outrank every other source, so a claude the admin starts by hand in a bash attach,
			// without the flags, still runs no hooks and no MCP servers
			{Src: filepath.Join(p.Exports, SettingsFile), Dst: ManagedDir + "/managed-settings.json", RO: true},
			// an empty git config over session-home's, in case a CLI drops GIT_CONFIG_GLOBAL for its own git
			{Src: filepath.Join(p.Exports, EmptyGitConfig), Dst: Home + "/" + GitConfigs[0], RO: true},
			{Src: filepath.Join(p.Exports, EmptyGitConfig), Dst: Home + "/" + GitConfigs[1], RO: true},
			{Src: p.Workspace, Dst: Workspace},
			{Src: p.Exports, Dst: Exports, RO: true},
			{Src: p.Codex, Dst: CodexHome},
		},
	}, nil
}

func homeOwned(dir string, uid int) error {
	var st unix.Stat_t
	if err := unix.Lstat(dir, &st); err != nil {
		return fmt.Errorf("no session-home %s (agent.add makes it): %v", dir, err)
	}
	if st.Mode&unix.S_IFMT != unix.S_IFDIR || int(st.Uid) != uid {
		return fmt.Errorf("session-home %s is not a dir owned by uid %d", dir, uid)
	}
	return nil
}

// fileMountpoint makes sure each dir of rel's path below home is a dir and rel a regular file, so a read-only bind has
// a target. A session that renamed a dir away gets a new one here: the bind covers it again.
func fileMountpoint(home, rel string, uid, gid int) error {
	d, err := unix.Open(home, unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
	if err != nil {
		return err
	}
	parts := strings.Split(rel, "/")
	for _, name := range parts[:len(parts)-1] {
		if err := unix.Mkdirat(d, name, 0o700); err == nil {
			unix.Fchownat(d, name, uid, gid, unix.AT_SYMLINK_NOFOLLOW)
		} else if !errors.Is(err, unix.EEXIST) {
			unix.Close(d)
			return err
		}
		next, err := unix.Openat(d, name, unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
		unix.Close(d)
		if err != nil {
			return fmt.Errorf("session-home ~/%s: %s is not a dir: %v", rel, name, err)
		}
		d = next
	}
	defer unix.Close(d)
	f, err := unix.Openat(d, parts[len(parts)-1], unix.O_CREAT|unix.O_WRONLY|unix.O_NOFOLLOW|unix.O_NONBLOCK|unix.O_CLOEXEC, 0o600)
	if err != nil {
		return fmt.Errorf("session-home ~/%s: %v", rel, err)
	}
	defer unix.Close(f)
	var st unix.Stat_t
	if err := unix.Fstat(f, &st); err != nil || st.Mode&unix.S_IFMT != unix.S_IFREG {
		return fmt.Errorf("session-home ~/%s is not a regular file", rel)
	}
	if int(st.Uid) != uid {
		unix.Fchown(f, uid, gid)
	}
	return nil
}

// codexHome is the session's fresh CODEX_HOME: rootd's config, and auth.json from session-home through a symlink, so
// a login or a token refresh lands in session-home (§4.2: only auth.json comes from session-home).
// shortcut: if Codex replaces auth.json by rename, the refresh stays in this dir and is lost at the end; copy it back
// (with the token scan's version tracking) if the real CLI does that.
func codexHome(p Paths, uid, gid int) error {
	if err := os.MkdirAll(p.Run, 0o711); err != nil {
		return err
	}
	// the agent's rootless podman makes the binds, so it must traverse to CODEX_HOME (rootd's UMask=0077)
	for _, d := range []string{filepath.Dir(p.Run), p.Run} {
		if err := os.Chmod(d, 0o711); err != nil {
			return err
		}
	}
	if err := os.Mkdir(p.Codex, 0o700); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(p.Codex, "config.toml"), []byte(CodexConfig), 0o444); err != nil {
		return err
	}
	if err := os.Chmod(filepath.Join(p.Codex, "config.toml"), 0o444); err != nil {
		return err
	}
	if err := os.Symlink(Home+"/.codex/auth.json", filepath.Join(p.Codex, "auth.json")); err != nil {
		return err
	}
	return os.Chown(p.Codex, uid, gid)
}

// RemoveRun removes the session's own dir (its CODEX_HOME).
func RemoveRun(p Paths) error { return os.RemoveAll(p.Run) }

// Podman runs a session as the agent's rootless podman container, in a transient unit of the agent's user manager,
// with a task's container flags (task.Argv: no network, no capabilities, a read-only root, the task seccomp profile).
// It mounts session-home where a task has its tmpfs HOME. The unit's stdio is the PTY rootd owns; podman -t relays it.
type Podman struct {
	Seccomp, Image string
	HostUsr        []string                 // the host dirs the stub task image mounts read-only (task.HostUsr)
	Ensure         func(agent string) error // the task image in the agent's podman, before its first session
}

func unit(id string) string { return "agentbox-attach-" + id + ".service" }

func userBus(agent string) []string { return []string{"--user", "-M", "ag-" + agent + "@"} }

func (Podman) Stop(agent, id string) error {
	return exec.Command("systemctl", append(userBus(agent), "stop", unit(id))...).Run()
}

// Argv is the session's one systemd-run.
func (p Podman) Argv(s Session) []string {
	a := append([]string{"systemd-run"}, userBus(s.Agent)...)
	a = append(a, "--wait", "--collect", "--quiet", "--service-type=exec", "--unit="+unit(s.ID),
		"-p", "TTYPath="+s.TTY, "-p", "StandardInput=tty", "-p", "StandardOutput=tty", "-p", "StandardError=tty",
		"-p", "Delegate=yes", "-p", "KillMode=mixed", "-p", "TimeoutStopSec="+strconv.Itoa(int(task.StopTimeout/time.Second)),
		"-p", "ExecStopPost=-"+task.Podman+" rm -f -i -t 0 attach-"+s.ID,
		task.Podman, "run", "--cgroups=split", "--rm", "-it", "--name", "attach-"+s.ID, "--network=none", "--userns=keep-id",
		"--security-opt=no-new-privileges", "--cap-drop=all", "--security-opt=seccomp="+p.Seccomp,
		"--read-only", "--tmpfs", "/tmp:rw,size=2g", "--pids-limit=4096", "--log-driver=none", "-w", s.Dir)
	for _, m := range s.Mounts {
		v := m.Src + ":" + m.Dst
		if m.RO {
			v += ":ro"
		}
		a = append(a, "-v", v)
	}
	a = append(a, "-v", task.Binary+":/usr/local/bin/agentbox:ro")
	for _, m := range p.HostUsr {
		a = append(a, "-v", m+":"+m+":ro")
	}
	for _, e := range s.Env {
		a = append(a, "-e", e)
	}
	return append(append(a, p.Image), s.Argv...)
}

func (p Podman) Run(ctx context.Context, s Session) error {
	if p.Ensure != nil {
		if err := p.Ensure(s.Agent); err != nil {
			return fmt.Errorf("task image: %v", err)
		}
	}
	return run(ctx, s.Agent, unit(s.ID), p.Argv(s))
}

// run runs systemd-run until the unit is gone. A canceled ctx stops the unit: killing systemd-run alone would leave it.
func run(ctx context.Context, agent, unit string, argv []string) error {
	c := exec.Command(argv[0], argv[1:]...)
	var stderr bytes.Buffer
	c.Stderr = &stderr
	if err := c.Start(); err != nil {
		return err
	}
	done := make(chan error, 1)
	go func() { done <- c.Wait() }()
	select {
	case err := <-done:
		return exitErr(err, &stderr)
	case <-ctx.Done():
		exec.Command("systemctl", append(userBus(agent), "stop", unit)...).Run()
		return exitErr(<-done, &stderr)
	}
}

func exitErr(err error, stderr *bytes.Buffer) error {
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		return fmt.Errorf("session exited %d: %s", ee.ExitCode(), bytes.TrimSpace(stderr.Bytes()))
	}
	return err
}
