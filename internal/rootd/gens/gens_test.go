func TestCmdlineGen(t *testing.T) {
	ok := "BOOT_IMAGE=/agentbox/gens/gen-2/vmlinuz-7.0.0-44-generic root=UUID=x ro panic=10 rootflags=subvol=@gen-2"
	if g, err := CmdlineGen(ok); err != nil || g != "gen-2" {
		t.Fatalf("CmdlineGen = %q, %v", g, err)
	}
	for _, bad := range []string{
		"root=UUID=x ro", // none
		"rootflags=subvol=@gen-1 rootflags=subvol=@gen-2", // two
		"rootflags=subvol=@home",                          // not a generation
		"rootflags=subvol=@gen-0",                         // gen numbers start at 1
		"rootflags=subvolid=5",                            // the top level
		"rootflags=subvol=@gen-2,compress=zstd",           // extra flags would change what boots
		"rootflags=subvol=@gen-12x",                       // trailing junk
	} {
		if g, err := CmdlineGen(bad); err == nil {
			t.Errorf("CmdlineGen(%q) = %q, want error", bad, g)
		}
	}
}

func TestEntries(t *testing.T) {
	if id := Entry("gen-12", "7.0.0-44-generic"); id != "agentbox-gen-12-7.0.0-44-generic" {
		t.Fatal(id)
	}
	if g, k, ok := ParseEntry("agentbox-gen-12-7.0.0-44-generic"); !ok || g != "gen-12" || k != "7.0.0-44-generic" {
		t.Fatalf("ParseEntry = %q %q %v", g, k, ok)
	}
	for _, bad := range []string{"", "agentbox-gen-x-7.0", "agentbox-gen-1-", "agentbox-gen-1-a'b", "Ubuntu", "agentbox-gen-01-7.0"} {
		if _, _, ok := ParseEntry(bad); ok {
			t.Errorf("ParseEntry(%q) accepted", bad)
		}
	}
}

// TestKernelOrder checks VerCmp against `sort -rV`, the order 09_agentbox lists kernels in.
func TestKernelOrder(t *testing.T) {
	names := []string{"vmlinuz-7.0.0-9-generic", "vmlinuz-7.0.0-44-generic", "vmlinuz-7.0.0-100-generic",
		"vmlinuz-7.0.0-44-generic-64k", "vmlinuz-7.1.0-1-generic", "vmlinuz-7.0.0-44~rc1-generic",
		"vmlinuz", "vmlinuz.old", "initrd.img-7.0.0-44-generic", "vmlinuz-bad'name"}
	want := []string{"7.1.0-1-generic", "7.0.0-100-generic", "7.0.0-44-generic-64k", "7.0.0-44-generic",
		"7.0.0-44~rc1-generic", "7.0.0-9-generic"}
	if got := Kernels(names); !slices.Equal(got, want) {
		t.Fatalf("Kernels = %v, want %v", got, want)
	}
	in := slices.Clone(want)
	slices.Reverse(in)
	out, err := exec.Command("sh", append([]string{"-c", `printf '%s\n' "$@" | sort -rV`, "sh"}, in...)...).Output()
	if err != nil {
		t.Skipf("sort -V: %v", err)
	}
	if got := strings.Fields(string(out)); !slices.Equal(got, want) {
		t.Errorf("sort -rV = %v, want %v", got, want)
	}
}

func TestGrubEnv(t *testing.T) {
	env := GrubEnv([]byte("# GRUB Environment Block\n# WARNING: Do not edit this file by tools other than grub-editenv!!!\nsaved_entry=agentbox-gen-1-7.0.0-43-generic\nnext_entry=\n" + strings.Repeat("#", 900)))
	if env["saved_entry"] != "agentbox-gen-1-7.0.0-43-generic" || env["next_entry"] != "" || len(env) != 2 {
		t.Fatalf("GrubEnv = %v", env)
	}
	if env := GrubEnv(nil); len(env) != 0 {
		t.Fatalf("empty grubenv = %v", env)
	}
}

func TestPrune(t *testing.T) {
	for _, tc := range []struct {
		name      string
		all       []int
		committed int
		protected []int
		want      []int
	}{
		{"first commit keeps gen-1", []int{1, 2}, 2, []int{2}, nil},
		{"two commits keep all three", []int{1, 2, 3}, 3, []int{3}, nil},
		{"third commit prunes gen-1", []int{1, 2, 3, 4}, 4, []int{4}, []int{1}},
		{"failed trial and interrupted build above committed go", []int{1, 2, 3, 5}, 2, []int{2}, []int{3, 5}},
		{"pending trial stays", []int{1, 2, 3}, 2, []int{2, 3}, nil},
		{"booted old generation stays", []int{1, 2, 3, 4, 5}, 5, []int{5, 1}, []int{2}},
		{"saved_entry ahead of committed after a crash mid-commit", []int{2, 3, 4, 5}, 4, []int{5, 4}, nil},
	} {
		if got := Prune(tc.all, tc.committed, tc.protected); !slices.Equal(got, tc.want) {
			t.Errorf("%s: Prune = %v, want %v", tc.name, got, tc.want)
		}
	}
}

